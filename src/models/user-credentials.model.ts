import {model, property} from '@loopback/repository';
import {BaseEntity} from '.';

@model()
export class UserCredentials extends BaseEntity {
  @property({
    type: 'number',
    id: true,
    generated: true,
  })
  id?: number;

  @property({
    type: 'string',
    required: true,
  })
  password: string;

  @property({
    type: 'number',
  })
  usersId?: number;

  constructor(data?: Partial<UserCredentials>) {
    super(data);
  }
}

